from components import (page, name_tape, statement, p, text_link, actions, tape_surface, org_tree, feature_list,
                        bullets, draft, note, todo)
from links import L

META = {"id": "I-1", "slug": "association", "title": "系學會", "owner": "院窗口", "site": "dept"}

# 除 draft() 外，本頁文字逐字取自現行「系學會」頁 https://wwwndmc.ndmutsgh.edu.tw/unit/100180/6796
# 現行頁整頁是一張長圖（網站圖1.png，alt「系學會」，更新日期 2025-10-28），文字無法被搜尋、也無法被螢幕報讀；
# 本頁把圖中文字轉成網頁文字。


def render():
    opening = "".join([
        statement(
            draft("系學會，由全系同學一起組成。"),
            "凡本學校護理學系之在學學生均為本會會員。",
        ),
        actions(text_link("系學會辦的活動", L("dept:I-2")), text_link("回校園生活", L("dept:I"))),
    ])

    charter = tape_surface(
        p("凡本學校護理學系之在學學生均為本會會員。會員皆享有參加系學會所舉辦之各項活動、出席會員大會，"
          "並享有發言提案、表決權、系學會選舉及被選舉權等權利。本會會員應履行會員大會之決議、"
          "參與及協助系學會規劃之活動，例：加冠典禮、校慶、國際交流等活動。"),
        p("會長及副會長於會員大會時由全系同學投票選出，主要負責系上每項活動之規劃及籌備，"
          "並掌握活動進度及活動後檢討，各組組長由會長指派協助學會事務運行，齊心完成各項活動。"),
    )

    chart = org_tree("會長・副會長", [
        ("行政組", [], "dept"),
        ("活動組", [], "dept"),
        ("總務組", [], "dept"),
        ("公關組", [], "dept"),
        ("國際事務組", [], "dept"),
    ])

    duties = feature_list([
        ("會長", "審查年度計劃與預算、對內主持會務，對外代表本會、了解並監督各組長達成工作目標。擔任學系會議的學生代表。",
         None, "dept", "會"),
        ("副會長", "協助會長處理各項會務，會長若未能執行職務時代理之，並於決策時提供建議。", None, "dept", "副"),
        ("行政組", "負責系學會各項會議之記錄，建置及更新系學會各項檔案資料。", None, "dept", "行"),
        ("活動組", "負責策劃及執行活動，並完成活動記錄。協助製作活動及各項宣傳海報與卡片，監督活動承辦細節。",
         None, "dept", "活"),
        ("總務組", "負責經費核銷與結報、建置系學會辦公室財產清冊。每個月與會長對帳，並於會員大會公布帳目。",
         None, "dept", "總"),
        ("公關組", "對外代表系學會發言，邀請及招待貴賓、師長參與活動，拓展及增進各校護理學系系學會之聯誼。",
         None, "dept", "公"),
        ("國際事務組", "負責辦理學系與國外學校交流之活動，接待國外貴賓、師長和與會朋友，協助籌備國際交流之計畫。",
         L("dept:I-3"), "dept", "國"),
    ])

    officers = "".join([
        todo("本屆會長、副會長的姓名、年級、一句話（想為同學做的事）與照片（院窗口向系學會取得）"),
        note("現行系學會圖片列出會長、副會長各一位（姓名前加屆別代號），圖片更新於 2025-10-28，可能已換屆。"
             "請院窗口向系學會取得本屆會長、副會長的姓名、年級與照片，並確認本人同意公開；"
             "年級請寫「二年級」這類說法，不要用屆別代號。收到後以 roster() 列出；各組組長若要列出，照同樣格式往下加。"),
    ])

    events = "".join([
        p(draft("系學會一年協助辦理的活動，依月份排列：")),
        bullets([
            "1月　大護盃",
            "1月　年初系大會",
            "2月　西北大學接待",
            "3月　加冠典禮",
            "4月　在校生關懷座談會",
            "6月　新生座談會",
            "6月　小畢典",
            "8月　國防迷彩天使災難救護營",
            "9月　年中系大會",
            "10月　系上迎新",
            "10月　學長姐Q&amp;A",
            "11月　八王子接待",
            "11月　校慶",
            "11月　在職座談會",
            "期中、期末　期中期末夜點",
        ]),
        actions(text_link("每項活動的介紹與照片", L("dept:I-2"))),
        note("活動名稱與月份取自現行系學會圖片「系學會協助辦理活動」；原圖「期中期末夜點」的月份標示不清，這裡改寫為「期中、期末」，請系學會確認。"),
    ])

    return page(
        opening,
        name_tape("組織章程"),
        charter,
        name_tape("組織架構"),
        chart,
        name_tape("部門介紹"),
        duties,
        *([name_tape("本屆幹部"), officers] if officers else []),
        name_tape("系學會協助辦理活動"),
        events,
        owner=META["owner"],
    )
