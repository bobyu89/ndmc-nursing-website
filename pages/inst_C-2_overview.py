from components import (page, name_tape, statement, p, h4, button, text_link, actions, timeline, feature_list,
                        bullets, tape_surface, draft, note)
from links import L
from tokens import SITE

META = {"id": "C-2", "slug": "overview", "title": "研究所簡介", "owner": "院窗口", "site": "inst"}

U_INST_HISTORY = SITE + "/unit/100181/6527"  # 研究所「歷史沿革」
U_GRAD = SITE + "/unit/100143/2004"          # 學校招生專區【碩、博班】


def _source(text, href, label):
    return p(draft(text) + "　" + text_link(label, href), muted=True)


def render():
    opening = statement(
        draft("國內護理碩士教育的先驅，培育會做研究的臨床護理人才。"),
        draft("護理研究所設於國防醫學大學護理學院，民國68年成立。碩士班分四個學組，"
              "讓已有臨床經驗的護理師，專精一個領域、學會做研究。"),
    )

    intro = tape_surface(
        p("民國68年為因應教育與研究之需求，設立護理研究所，成為國內護理碩士教育之先驅。"),
        p(draft("【研究所簡介正文】研究所的定位、師資與研究環境、和三軍總醫院的合作，約 200–300 字。")),
    )

    research = "".join([
        p(draft("研究所是護理學院研究內容的主站。研究方向、各研究團隊與指導教師目前收學生的主題，"
                "都整理在「研究成果」各頁，這裡只做入口。")),
        actions(text_link("研究領域", L("inst:F-1")), text_link("研究發表", L("inst:F-2")),
                text_link("學術活動紀錄", L("inst:F-3"))),
    ])

    # 年份與說明原文照錄自研究所「歷史沿革」頁（與學院歷史沿革同文）；年份圓章為民國年加 1911 換算的西元年。
    events = timeline([
        ("1943", "上海江灣「高級護理職業班」",
         "國防醫學大學護理學院護理學系源於上海江灣之「高級護理職業班」，由 周美玉將軍於民國32年創立，"
         "招收初中畢業之學生，修業四年半，為我國最早開辦之護理人員職業教育訓練班。", "college"),
        ("1947", "設立護理學系",
         "民國36年周將軍更進而設立護理學系，成為我國首創之護理高等學府。", "dept"),
        ("1949", "遷台",
         "民國38年護理學系隨國防醫學院遷台至台北水源地。"),
        ("1979", "設立護理研究所",
         "民國68年為因應教育與研究之需求，設立護理研究所，成為國內護理碩士教育之先驅。", "inst"),
        ("1999", "遷至內湖",
         "民國88年校址遷移至內湖的國防醫學中心，以優良的師資與嶄新的硬體設備，訓練優秀的護理專業人才，"
         "繼續發揮百年樹人的志業。"),
        ("2025", "成立護理學院",
         "民國114年成立護理學院，成為推動臺灣高等護理教育的先鋒。", "college"),
    ])

    goals = bullets([
        draft("【目標一】培育具進階護理能力的臨床護理人才。"),
        draft("【目標二】培育能提出臨床問題、設計並執行研究的護理人員。"),
        draft("【目標三】培育能投入護理教育與軍陣護理的人才。"),
    ])

    # 分組原文照錄自《116 學年度博、碩士班招生簡章》（見學院招生專區頁 F 的整理）。
    groups = feature_list([
        ("成人暨老人護理學組", draft("成人與老年病人的臨床照護與研究。"), None, "inst", "成"),
        ("婦兒護理學組", draft("孕產婦、新生兒與兒童的照護與研究。"), None, "inst", "婦"),
        ("精神衛生護理學組", draft("精神健康與心理照護的臨床與研究。"), None, "inst", "精"),
        ("專科護理師組", draft("培養專科護理師，修讀進階專科護理課程與實習。"), None, "inst", "專"),
    ])

    doctoral = "".join([
        p(draft("學校招生專區〈【碩、博班】〉已列出護理研究所博士班。博士班的定位、研究方向與修業方式整理中。")),
        note("博士班如何對外介紹，請院窗口與研究所確認後提供：博士班成立年份、招生對象、研究方向、修業年限。"
             "確認前本段維持草稿。"),
    ])

    return page(
        opening,
        name_tape("研究所簡介"),
        intro,
        note("現行研究所網站只有〈歷史沿革〉一段文字，沒有研究所簡介正文。請院窗口提供簡介 200–300 字；"
             "專任教師人數、在學研究生人數、畢業生人數若要放，請附資料來源。"),
        name_tape("研究特色"),
        research,
        name_tape("發展沿革"),
        events,
        _source("以上摘自護理研究所〈歷史沿革〉。", U_INST_HISTORY, "原頁面"),
        note("現行〈歷史沿革〉是學院共用的一段文字，研究所自己的里程碑只有民國68年。請院窗口補齊研究所的年份事件，"
             "例如各學組、專科護理師組、博士班的設立年份，以及歷次系所評鑑；沒有文件佐證的年份請勿填入。"),
        name_tape("教育目標"),
        goals,
        note("現行網站找不到研究所教育目標的正式文字（研究生專區只提到「達到本所培訓進階護理師之目標」）。"
             "請院窗口依研究生手冊或評鑑資料提供正式教育目標，上方三條為草稿，收到後整段替換。"),
        name_tape("碩士班與博士班"),
        h4("碩士班"),
        groups,
        _source("學組名稱摘自學校招生專區與《116 學年度博、碩士班招生簡章》。", U_GRAD, "碩博士班招生簡章"),
        h4("博士班"),
        doctoral,
        actions(button("招生資訊", L("inst:D-1")), text_link("修業規定", L("inst:E-2"))),
        owner=META["owner"],
    )
