def _quotes(*items):
    """One brochure block per answer: [(who or None, verbatim text), ...], set below the plain explanation."""
    lines = [(f"<strong>{who}：</strong>" if who else "") + f"「{text}」" for who, text in items]
    return source_quote("<br>".join(lines), SRC)


def _two(mil, vac):
    """A comparison cell: 軍費生 line, then 代訓生 line."""
    return f"<strong>軍費生：</strong>{mil}<br><strong>代訓生：</strong>{vac}"


def _next():
    """The calm next step, set right under the answer line."""
    return p(text_link("有疑問可以問誰：招生與學系電話", CONTACT), muted=True)


def _ask(text):
    """Calm closing step for answers about obligations: who to ask next."""
    return p(draft(text) + "　" + text_link("聯絡電話：有問題可以問誰", CONTACT))


