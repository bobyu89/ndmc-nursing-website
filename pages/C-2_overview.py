from components import (page, name_tape, statement, p, split, photo, button, text_link, actions, route_list,
                        tape_surface, draft, note)
from links import L

META = {"id": "C-2", "slug": "overview", "title": "學院簡介", "owner": "哲君"}

# 院徽圖檔：現行「歷史沿革」頁（unit/100010/6804）所用的 護理學院LOGO.png。
EMBLEM = "https://wwwndmc.ndmutsgh.edu.tw/files/web/192/contents/100010/%E8%AD%B7%E7%90%86%E5%AD%B8%E9%99%A2LOGO.png"


def render():
    opening = statement(
        draft("培育能照護病人、也能執行任務的軍護人才。"),
        draft("國防醫學大學護理學院是國內培育軍護人才的護理學院，下設護理學系（學士班）與護理研究所（碩士班）。"
              "學生在校學護理，也接受軍事訓練，畢業後以護理軍官的身分投入部隊與醫院。"),
    )

    # 以下兩段取自現行「歷史沿革」頁（unit/100010/6804），原文照錄。
    roots = tape_surface(
        p("國防醫學大學護理學院護理學系源於上海江灣之「高級護理職業班」，由 周美玉將軍於民國32年創立，"
          "招收初中畢業之學生，修業四年半，為我國最早開辦之護理人員職業教育訓練班。"
          "民國36年周將軍更進而設立護理學系，成為我國首創之護理高等學府。"),
        p("民國68年為因應教育與研究之需求，設立護理研究所，成為國內護理碩士教育之先驅。"
          "民國114年成立護理學院，成為推動臺灣高等護理教育的先鋒。"),
        actions(text_link("歷史沿革與軍護傳承", L("C-3"))),
    )

    military = "".join([
        p(draft("軍陣護理，是在部隊、野戰、艦艇、航空與災區等特殊環境中提供照護。"
                "這是本院和一般護理學校最不一樣的地方。")),
        p(draft("課程把軍事訓練和臨床護理放在一起，實習在三軍總醫院等國軍醫院進行，"
                "並以戰傷與災難護理為教學與研究重點。")),
        actions(text_link("學術研究", L("E-2"))),
    ])

    units = route_list([
        ("護理學系", "學士班：護理基礎、臨床實習與軍陣護理", L("D-1")),
        ("護理研究所", "碩士班：臨床護理組、專科護理師組", L("D-2")),
    ])

    # 院徽說明取自現行「歷史沿革」頁（unit/100010/6804），原文照錄。
    emblem = split(
        photo(EMBLEM, "護理學院院徽：圓形徽章，中央為紅、紫、白三朵鬱金香，下方標示 1947，"
                      "外環寫國防醫學大學護理學院中英文校名", "1/1", fit="contain"),
        "".join([
            p("院徽代表護理學院的教學理念為尊重人與環境的協調平衡，以太極圖形來象徵身、心、靈及社會的健康，"
              "同時也達到教學的完滿圓融境界；三朵盛開的花則代表教師們發揮教學、服務及研究的三項任務，"
              "蘊育出許許多多傑出的學子。"),
            p("鬱金香被視為勝利和美好的象徵，同時它還代表著愛的表白和永恆的祝福，不同的顏色有不同的意義分別是："
              "「紅色」象徵愛的宣言、喜悅、熱愛，「紫色」象徵忠貞的愛，「白色」象徵純情、純潔。"),
        ]),
        cols=(4, 8), align="start",
    )

    return page(
        opening,
        note("請哲君依《護理學院年報》補齊：學院簡介正文（300–500 字）、在校學生人數、專任教師人數、"
             "主要臨床實習醫院名單。年報上沒有的數字不要放。軍陣護理一段為草稿，請確認用詞。"),
        name_tape("學院的來歷"),
        roots,
        name_tape("軍陣護理"),
        military,
        name_tape("學院下設單位"),
        units,
        name_tape("院徽"),
        emblem,
        actions(button("招生專區", L("F")), text_link("組織架構", L("C-4"))),
        owner=META["owner"],
    )
